import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = path.join(root, 'contracts', 'watch-record.schema.json');
const tsPath = path.join(root, 'src', 'shared', 'types', 'watchRecord.generated.ts');
const rustPath = path.join(root, 'src-tauri', 'src', 'watch_record_generated.rs');
const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const check = process.argv.includes('--check');

const tsType = type => ({ string: 'string', bool: 'boolean', i32: 'number', i64: 'number', f64: 'number', RecordStatus: 'Status', MediaType: 'MediaType', TmdbMediaKind: 'TmdbMediaKind', SeriesRecordKind: 'SeriesRecordKind' })[type];
const rustType = type => ({ string: 'String', bool: 'bool', i32: 'i32', i64: 'i64', f64: 'f64', RecordStatus: 'RecordStatus', MediaType: 'String', TmdbMediaKind: 'String', SeriesRecordKind: 'String' })[type];
const quote = value => JSON.stringify(value);
const screamingSnake = value => value.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();

const enumLines = Object.values(schema.enums).map(item => {
  const values = item.values.map(value => quote(value.wire)).join(' | ');
  const constant = screamingSnake(item.typescriptName);
  return `export const ${constant}_VALUES = [${item.values.map(value => quote(value.wire)).join(', ')}] as const;\nexport type ${item.typescriptName} = typeof ${constant}_VALUES[number];`;
});
const isTsNullable = field => field.tsNullable ?? field.nullable;
const tsFields = schema.watchRecord.map(field => `  ${field.wire}${field.tsOptional ? '?' : ''}: ${tsType(field.type)}${isTsNullable(field) ? ' | null' : ''};`);
const mutable = schema.watchRecord.filter(field => field.mutable);
const updateFields = mutable.map(field => {
  const nullable = field.mutable === 'patch' ? ' | null' : '';
  return `  ${field.wire}?: ${tsType(field.type)}${nullable};`;
});
const ts = `// @generated by scripts/generate-contracts.mjs from contracts/watch-record.schema.json\n// Do not edit by hand. Run npm run contracts:generate.\n\n${enumLines.join('\n')}\n\nexport interface WatchRecord {\n${tsFields.join('\n')}\n}\n\nexport interface UpdateWatchRecord {\n${updateFields.join('\n')}\n}\n\nexport const WATCH_RECORD_UPDATE_FIELDS = ${JSON.stringify(mutable.map(field => field.wire), null, 2)} as const;\n`;

const status = schema.enums.RecordStatus;
const rustEnum = `#[derive(Debug, Serialize, Deserialize, Clone, PartialEq)]\npub enum RecordStatus {\n${status.values.map(value => `    #[serde(rename = ${quote(value.wire)})]\n    ${value.rust},`).join('\n')}\n}\n\nimpl ToSql for RecordStatus {\n    fn to_sql(&self) -> rusqlite::Result<ToSqlOutput<'_>> {\n        Ok(ToSqlOutput::from(match self {\n${status.values.map(value => `            Self::${value.rust} => ${quote(value.wire)},`).join('\n')}\n        }))\n    }\n}\n\nimpl FromSql for RecordStatus {\n    fn column_result(value: ValueRef<'_>) -> FromSqlResult<Self> {\n        value.as_str().and_then(|value| match value {\n${status.values.map(value => `            ${quote(value.wire)} => Ok(Self::${value.rust}),`).join('\n')}\n            _ => Err(rusqlite::types::FromSqlError::InvalidType),\n        })\n    }\n}`;
const rustRecordFields = schema.watchRecord.map(field => {
  const attrs = field.default ? '    #[serde(default)]\n' : '';
  const type = field.nullable ? `Option<${rustType(field.type)}>` : rustType(field.type);
  return `${attrs}    pub ${field.rust}: ${type},`;
});
const rustUpdateFields = mutable.map(field => {
  const attrs = field.mutable === 'patch' ? '    #[serde(default)]\n' : '';
  const type = field.mutable === 'patch' ? `Patch<${rustType(field.type)}>` : `Option<${rustType(field.type)}>`;
  return `${attrs}    pub ${field.rust}: ${type},`;
});
const rustValueConstants = Object.values(schema.enums).map(item => `#[allow(dead_code)]\npub const ${screamingSnake(item.typescriptName)}_VALUES: &[&str] = &[${item.values.map(value => quote(value.wire)).join(', ')}];`).join('\n');
const rust = `// @generated by scripts/generate-contracts.mjs from contracts/watch-record.schema.json\n// Do not edit by hand. Run npm run contracts:generate.\n\nuse rusqlite::types::{FromSql, FromSqlResult, ToSqlOutput, ValueRef};\nuse rusqlite::ToSql;\nuse serde::{Deserialize, Serialize};\n\n${rustValueConstants}\n\n${rustEnum}\n\n#[derive(Debug, Serialize, Deserialize, Clone)]\n#[serde(rename_all = "camelCase")]\npub struct WatchRecord {\n${rustRecordFields.join('\n')}\n}\n\n#[derive(Debug, Default, Deserialize, Clone, PartialEq)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct UpdateWatchRecord {\n${rustUpdateFields.join('\n')}\n}\n\n#[allow(dead_code)]\npub const WATCH_RECORD_UPDATE_FIELDS: &[&str] = &[\n${mutable.map(field => `    ${quote(field.wire)},`).join('\n')}\n];\n`;

for (const [target, content] of [[tsPath, ts], [rustPath, rust]]) {
  if (check) {
    const existing = await readFile(target, 'utf8').catch(() => '');
    if (existing !== content) {
      console.error(`Generated contract is stale: ${path.relative(root, target)}`);
      process.exitCode = 1;
    }
  } else {
    await writeFile(target, content, 'utf8');
  }
}

if (check) {
  const updateSource = await readFile(path.join(root, 'src-tauri', 'src', 'db_atomic_update.rs'), 'utf8');
  const mappedFields = new Set([...updateSource.matchAll(/(?:optional|patch)!\([^,]+,\s*"([^"]+)"/g)].map(match => match[1]));
  if (updateSource.includes('clauses.push("status = ?"')) mappedFields.add('status');
  const expected = mutable.map(field => field.wire);
  const missing = expected.filter(field => !mappedFields.has(field));
  const extra = [...mappedFields].filter(field => !expected.includes(field));
  if (missing.length || extra.length) {
    console.error(`Rust update mapping drift (missing: ${missing.join(', ') || 'none'}; extra: ${extra.join(', ') || 'none'})`);
    process.exitCode = 1;
  }
}
